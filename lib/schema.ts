/**
 * Reusable schema.org builders. Entities are linked by @id so Google sees one Person and
 * one business across every page instead of many disconnected copies.
 *
 * Rules: only facts already published on the site. No Review or AggregateRating markup.
 */
import { SITE_URL, SITE_NAME, AUTHOR_NAME, AUTHOR_ROLE, SOCIAL_LINKS, STATIC_CONTENT_UPDATED, absoluteUrl, toSchemaDateTime } from "@/lib/site";
import { services } from "@/lib/data/services";

export const PERSON_ID = `${SITE_URL}/#person`;
export const WEBSITE_ID = `${SITE_URL}/#website`;
export const BUSINESS_ID = `${SITE_URL}/#business`;
export const PROFILE_PAGE_ID = `${SITE_URL}/#profilepage`;
export const ORGANIZATION_ID = `${SITE_URL}/#organization`;

/** Square 512x512 brand icon generated by scripts/generate-icons.mjs (app/icon.png). */
const LOGO_URL = absoluteUrl("/icon.png");
const HOME_URL = `${SITE_URL}/`;

type Json = Record<string, unknown>;

const CONTEXT = "https://schema.org";
// The US is the primary market (keyword pages target it); clients come from anywhere.
const AREA_SERVED = [{ "@type": "Country", name: "United States" }, "Worldwide"];

export function personSchema(): Json {
  return {
    "@context": CONTEXT,
    "@type": "Person",
    "@id": PERSON_ID,
    name: AUTHOR_NAME,
    alternateName: ["Sani", "Abdul Kaiyum"],
    jobTitle: AUTHOR_ROLE,
    description:
      "n8n developer, full-stack developer and growth engineer building fast websites, SEO content and lead automation for US law firms and local businesses.",
    url: SITE_URL,
    image: absoluteUrl("/images/portrait-suit-1.png"),
    email: "contact.sani@proton.me",
    sameAs: Object.values(SOCIAL_LINKS),
    worksFor: [
      { "@id": BUSINESS_ID },
      { "@type": "Organization", name: "GrowMinion", url: "https://growminion.com/" },
    ],
    knowsAbout: [
      "n8n",
      "Workflow automation",
      "Full-stack development",
      "Technical SEO",
      "Lead generation",
      "Next.js",
      "React",
      "TypeScript",
      "Node.js",
      "GoHighLevel",
      "SEO copywriting",
    ],
  };
}

/** Homepage only. Google reads the site name shown in search results from this node. */
export function websiteSchema(): Json {
  return {
    "@context": CONTEXT,
    "@type": "WebSite",
    "@id": WEBSITE_ID,
    name: SITE_NAME,
    alternateName: ["Sani Forge", "saniforge.space"],
    url: HOME_URL,
    inLanguage: "en",
    description:
      "Portfolio and blog of Abdul Kaiyum Sani: n8n developer, full-stack developer and growth engineer.",
    publisher: { "@id": ORGANIZATION_ID },
    author: { "@id": PERSON_ID },
  };
}

/** Homepage only. Supplies the logo Google can show for the site. */
export function organizationSchema(): Json {
  return {
    "@context": CONTEXT,
    "@type": "Organization",
    "@id": ORGANIZATION_ID,
    name: SITE_NAME,
    url: HOME_URL,
    logo: { "@type": "ImageObject", url: LOGO_URL, width: 512, height: 512 },
    founder: { "@type": "Person", "@id": PERSON_ID, name: AUTHOR_NAME },
    sameAs: [SOCIAL_LINKS.linkedin, SOCIAL_LINKS.github, SOCIAL_LINKS.facebook],
  };
}

export function professionalServiceSchema(): Json {
  return {
    "@context": CONTEXT,
    "@type": "ProfessionalService",
    "@id": BUSINESS_ID,
    name: SITE_NAME,
    url: SITE_URL,
    description:
      "Full-stack web development, n8n automation, GoHighLevel lead generation, SaaS development, copywriting and SEO content for US businesses.",
    logo: LOGO_URL,
    image: absoluteUrl("/opengraph-image"),
    email: "contact.sani@proton.me",
    founder: { "@id": PERSON_ID },
    areaServed: AREA_SERVED,
    sameAs: Object.values(SOCIAL_LINKS),
    serviceType: services.map((s) => s.label),
    knowsLanguage: "en",
  };
}

/** Homepage only: tells Google the site's front page is the profile of the Person, published by the business. */
export function profilePageSchema(): Json {
  return {
    "@context": CONTEXT,
    "@type": "ProfilePage",
    "@id": PROFILE_PAGE_ID,
    url: SITE_URL,
    name: `${AUTHOR_NAME} | ${AUTHOR_ROLE}`,
    inLanguage: "en",
    dateModified: toSchemaDateTime(STATIC_CONTENT_UPDATED),
    isPartOf: { "@id": WEBSITE_ID },
    mainEntity: { "@id": PERSON_ID },
    about: { "@id": PERSON_ID },
    publisher: { "@id": BUSINESS_ID },
  };
}

export type Crumb = { name: string; path: string };

/** Home is prepended automatically. */
export function breadcrumbSchema(crumbs: Crumb[]): Json {
  const all = [{ name: "Home", path: "/" }, ...crumbs];
  return {
    "@context": CONTEXT,
    "@type": "BreadcrumbList",
    itemListElement: all.map((c, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: c.name,
      item: absoluteUrl(c.path),
    })),
  };
}

type ArticleInput = {
  type: "BlogPosting" | "Article";
  headline: string;
  description: string;
  path: string;
  images: string[];
  datePublished?: string;
  dateModified?: string;
  section?: string;
  keywords?: string[];
};

export function articleSchema({ type, headline, description, path, images, datePublished, dateModified, section, keywords }: ArticleInput): Json {
  const url = absoluteUrl(path);
  return {
    "@context": CONTEXT,
    "@type": type,
    headline: headline.replace(/[“”"]/g, "").slice(0, 110),
    description,
    image: images.map(absoluteUrl),
    ...(datePublished ? { datePublished: toSchemaDateTime(datePublished) } : {}),
    ...(dateModified ?? datePublished ? { dateModified: toSchemaDateTime((dateModified ?? datePublished)!) } : {}),
    author: { "@type": "Person", "@id": PERSON_ID, name: AUTHOR_NAME, url: SITE_URL },
    publisher: {
      "@type": "Organization",
      "@id": BUSINESS_ID,
      name: SITE_NAME,
      url: SITE_URL,
      logo: { "@type": "ImageObject", url: LOGO_URL, width: 512, height: 512 },
    },
    mainEntityOfPage: { "@type": "WebPage", "@id": url },
    url,
    inLanguage: "en",
    ...(section ? { articleSection: section } : {}),
    ...(keywords && keywords.length ? { keywords: keywords.join(", ") } : {}),
  };
}

type ServiceInput = {
  name: string;
  description: string;
  path: string;
  serviceType?: string;
  offers?: { name: string; description: string }[];
};

export function serviceSchema({ name, description, path, serviceType, offers }: ServiceInput): Json {
  return {
    "@context": CONTEXT,
    "@type": "Service",
    name,
    description,
    url: absoluteUrl(path),
    serviceType: serviceType ?? name,
    provider: { "@type": "ProfessionalService", "@id": BUSINESS_ID, name: SITE_NAME, url: SITE_URL },
    areaServed: AREA_SERVED,
    ...(offers && offers.length
      ? {
          hasOfferCatalog: {
            "@type": "OfferCatalog",
            name: `${name} services`,
            itemListElement: offers.map((o) => ({
              "@type": "Offer",
              itemOffered: { "@type": "Service", name: o.name, description: o.description },
            })),
          },
        }
      : {}),
  };
}

export function faqSchema(faqs: { q: string; a: string }[]): Json {
  return {
    "@context": CONTEXT,
    "@type": "FAQPage",
    mainEntity: faqs.map((f) => ({ "@type": "Question", name: f.q, acceptedAnswer: { "@type": "Answer", text: f.a } })),
  };
}
